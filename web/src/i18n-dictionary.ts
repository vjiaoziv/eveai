export type TranslationKey = keyof typeof RU;

/**
 * Locale lookup usable outside React (api.ts runs in module scope).
 * Placeholder substitution is identical to the provider `t`, so the same key
 * renders the same string with or without a React tree.
 */
/**
 * Locale for code that runs outside React (module-level helpers, api.ts).
 * Reads the same storage key the provider writes, so both stay in sync.
 */
export function readStoredLocale(): Locale {
  try {
    const saved = globalThis.localStorage?.getItem(LOCALE_STORAGE_KEY);
    if (saved === 'zh' || saved === 'en' || saved === 'ru') return saved;
  } catch {
    // Storage unavailable (tests, SSR): fall back to the provider default.
  }
  return 'zh';
}

export function translateOutOfReact(
  key: TranslationKey,
  locale: Locale,
  params?: Record<string, string>,
): string {
  const template = locale === 'zh' ? ZH[key] : locale === 'en' ? EN[key] : RU[key];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => params[name] ?? match);
}
